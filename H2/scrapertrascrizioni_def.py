# Funzione corretta per leggere i file .vtt ed estrarre testo e timestamp
def parse_vtt_clean(vtt_content, video_id):
    data = []
    lines = vtt_content.strip().split('\n')
    i = 1
    while i < len(lines):
        if '-->' in lines[i]:
            timestamp = lines[i].strip()
            sentence_parts = []
            i += 1
            while i < len(lines) and '-->' not in lines[i]:
                if lines[i].strip() and not lines[i].strip().isdigit():
                    sentence_parts.append(lines[i].strip())
                i += 1
            sentence = ' '.join(sentence_parts)
            data.append({"id": video_id, "timestamp": timestamp, "sentence": sentence})
        else:
            i += 1
    return data

cleaned_transcript_data = []

# Ciclo di download per ogni video trovato
print("Scaricamento trascrizioni in corso...")
for video in tqdm(versionId):
    try:
        # Estrae le 4 cifre dopo "pm" dall'identificativo
        v_id = video["versionIdentifier"]
        pm_index = v_id.find("pm")

        if pm_index != -1:
            pm_digits = v_id[pm_index+2:pm_index+6]
            url = f"https://hls.ted.com/project_masters/{pm_digits}/subtitles/en/full.vtt"

            response = requests.get(url)
            if response.status_code == 200:
                vtt_content = response.text
                parsed_data = parse_vtt_clean(vtt_content, video["id"])
                # Aggiunge le frasi alla lista finale
                cleaned_transcript_data.extend(parsed_data)
    except Exception as e:
        pass

# Salvataggio nel file CSV
df = pd.DataFrame(cleaned_transcript_data)
